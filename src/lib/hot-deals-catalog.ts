export function hotDealModelKey(name: string): string | null {
  const match = name.toLowerCase().match(/\biphone\s*(\d+)\s*(pro\s*max|promax|pro)?\b/);
  if (!match) return null;
  const tier = (match[2] || '').replace(/\s+/g, '');
  return `iphone-${match[1]}-${tier}`;
}
